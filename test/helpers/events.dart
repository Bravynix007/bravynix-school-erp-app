import 'package:bravynix_school_erp/features/events/domain/event.dart';

SchoolEvent schoolEvent({
  String id = 'e1',
  String title = 'Annual Day',
  bool isHoliday = false,
  String? venue = 'Auditorium',
  String? description = 'Prizes and a play.',
  List<String> classIds = const [],
  HolidayType? holidayType,
  bool forStudents = false,
  bool forStaff = false,
  DateTime? startDate,
  DateTime? endDate,
  String? presetImageCode,
  EventImage? image,
  bool canEdit = false,
  EventScope scope = EventScope.society,
  String? institutionId,
}) => SchoolEvent(
  id: id,
  title: title,
  description: description,
  venue: venue,
  startDate: startDate ?? DateTime(2026, 11, 20),
  endDate: endDate ?? DateTime(2026, 11, 20),
  durationLabel: '1 Day Event',
  audience: EventAudience.everyone,
  scope: scope,
  institutionId: institutionId,
  presetImageCode: presetImageCode,
  image: image,
  isHoliday: isHoliday,
  holidayType: holidayType,
  holidayForStudents: forStudents,
  holidayForStaff: forStaff,
  holidayClassIds: classIds,
  canEdit: canEdit,
  version: 1,
);

